/** Uma (ou mais) imagens por grupo já existente — capa + amostra de cada produto/item */
function cardSlidesFromGroups(
  groups: Record<string, readonly string[]>,
  cover: string,
  perGroup = 1,
): string[] {
  const samples = Object.values(groups).flatMap((imgs) =>
    imgs.slice(0, perGroup),
  );
  return [...new Set([cover, ...samples])];
}

